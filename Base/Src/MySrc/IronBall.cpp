// デフォルトのファクトリ
std::function<bool(CIronBall*)> CIronBall::s_fpDefaultFactory =
[](CIronBall* pImpact) -> bool
{
	// 初期化処理
	pImpact->Initialize();

	return true;
};

//============================================================================
// コンストラクタ
//============================================================================
CIronBall::CIronBall(OBJ::TYPE Type, OBJ::LAYER Layer)
	: CObjectX(Type, Layer)
	, m_nFrame(0)
	, m_Velocity(0.0f)
	, m_NowFrame(0)
{}

//============================================================================
// デストラクタ
//============================================================================
CIronBall::~CIronBall()
{
}

//============================================================================
// 初期化処理
//============================================================================
bool CIronBall::Initialize()
{
	// オブジェクト(Xモデル)の初期化処理
	if (FAILED(CObjectX::Initialize()))
	{
		return false;
	}

	return true;
}

//============================================================================
// 終了処理
//============================================================================
void CIronBall::Finalize()
{
	// オブジェクト(Xモデル)の終了処理
	CObjectX::Finalize();
}

//============================================================================
// 更新処理
//============================================================================
void CIronBall::Update()
{

	// オブジェクト(Xモデル)の更新処理
	// 行列の再計算を含んでいるため更新処理の終わりに呼びます
	CObjectX::Update();

}

//============================================================================
// 描画処理
//============================================================================
void CIronBall::Draw()
{

	// オブジェクト(Xモデル)の描画処理
	CObjectX::Draw();
}